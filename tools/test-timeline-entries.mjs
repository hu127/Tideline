import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {transform} from 'esbuild';
const {code} = await transform(await readFile(new URL('../src/pages/timeline-entries.ts',import.meta.url),'utf8'),{loader:'ts',format:'esm'});
const {timelineEntries} = await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
const events=[{id:'meeting',date:'2026-11-18',time:'14:00',title:'Meeting',description:''}];
const journal=[{id:'1',time:'15:30',text:'1:1 conversation until 17:30'},{id:'2',time:'13:20',text:'Paused study'},{id:'3',time:'',text:'Undated reflection'},{id:'4',time:'24:30',text:'Invalid time'},{id:'5',time:'9:05',text:'Morning note'},{id:'6',time:'12:99',text:'Invalid minute'},{id:'7',time:'14:00',text:'A note at the same time as the meeting'}];
const before=JSON.stringify({events,journal});
const result=timelineEntries('2026-11-18',events,journal);
assert.deepEqual(result.map(x=>x.time),['09:05','13:20','14:00','14:00','15:30']);
assert.equal(result.filter(x=>x.kind==='journal').length,4);
assert.equal(new Set(result.map(x=>x.id)).size,result.length);
assert.equal(result.at(-1).title,journal[0].text);
assert.equal(JSON.stringify({events,journal}),before);
assert.deepEqual(timelineEntries('2026-11-18',events,journal),result);
assert.deepEqual(timelineEntries('2026-11-18',[],[]),[]);
console.log('PASS: timed journal captions, chronology, same-time events, normalized time, invalid/untimed filtering, distinct IDs, no source mutation');

const note=(id,time,action,topic='KV',seconds='00')=>({id,time,text:`Inference 学习｜${action}｜${topic}｜累计有效 97分2秒（${time}:${seconds}）`});
const study=[note('s','14:00','开始学习'),note('p','15:35','暂停学习'),note('r','15:50','恢复学习'),note('p2','16:37','暂停学习','KV','04'),{id:'x',time:'16:37',text:'Unrelated note'},note('r2','16:38','恢复学习','KV','25'),note('e','17:01','结束学习')];
const original=JSON.stringify(study);
const grouped=timelineEntries('2026-11-19',[],study);
assert.equal(grouped.length,6);
const pair=grouped.find(e=>e.endTime);
assert.equal(pair.time,'16:37');assert.equal(pair.endTime,'16:38');
assert.match(pair.title,/短暂暂停后恢复 · 1分21秒/);
assert.match(pair.description,/暂停学习/);assert.match(pair.description,/恢复学习/);
assert.ok(grouped.some(e=>e.time==='15:35'&&!e.endTime));
assert.ok(grouped.some(e=>e.time==='15:50'&&!e.endTime));
assert.equal(JSON.stringify(study),original);
assert.equal(timelineEntries('2026-11-19',[],[note('p','16:00','暂停学习','A'),note('r','16:01','恢复学习','B')]).length,2);
assert.equal(timelineEntries('2026-11-19',[],[note('p','16:00','暂停学习'),note('e','16:00','结束学习'),note('r','16:01','恢复学习')]).length,3);
assert.equal(timelineEntries('2026-11-19',[],[note('p','16:00','暂停学习'),note('r','16:02','恢复学习','KV','01')]).length,2);
assert.equal(timelineEntries('2026-11-19',[],[note('p','16:00','暂停学习'),note('r','16:02','恢复学习')]).length,1);
console.log('PASS: only short pause/resume pairs merge, exact seconds, two-minute threshold, distinct topics and session boundaries, source preservation');
